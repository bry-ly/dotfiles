#!/usr/bin/env bash
# sync.sh — pull the live system config into this repo.
#
# Idempotent. Safe to re-run any time. Never deletes from the source.
# Run this after changing anything in ~ and you want it captured here.

set -euo pipefail

DOTDIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HOME_DIR="${DOTDIR}/home"
CONF_DIR="${DOTDIR}/config"
THEME_DIR="${DOTDIR}/themes"
ASSET_DIR="${DOTDIR}/assets"
PKG_DIR="${DOTDIR}/packages"

log()  { printf '\033[1;34m::\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31mxx\033[0m %s\n' "$*" >&2; exit 1; }

command -v rsync >/dev/null || die "rsync is required"

mkdir -p "$HOME_DIR" "$CONF_DIR" "$THEME_DIR" "$ASSET_DIR" "$PKG_DIR"

# ---------------------------------------------------------------------------
# Application state: regenerated by the apps themselves, huge, and never part
# of the reproducible setup. Everything listed here is excluded by name.
# ---------------------------------------------------------------------------
APP_STATE=(
  mozilla Figma equibop Google spotifast awww
  net.imput.helium helium obsidian opencode ai.opencode.desktop Todoist
  BetterDiscord Equicord Vencord legcord vesktop heroic sidra
  Discord telegram-desktop TelegramDesktop Spotify spotify
  onlyoffice VirtualBox obs-studio figma QtProject qtengine deltarunner pip
  manicode youtube
)

# Apps that ARE worth tracking, but only a hand-picked subset of their config.
# The bulk (caches, histories, extension payloads) is state, not setup.
# format: <config-dir-name>|<path-inside-it>
EDITOR_SUBSET=(
  "VSCodium|User/settings.json"
  "VSCodium|User/keybindings.json"
  "VSCodium|User/snippets"
  "VSCodium|User/tasks.json"
  "VSCodium|User/Theme"
  "Code|User/settings.json"
  "Code|User/keybindings.json"
  "Code|User/snippets"
  "Code|User/tasks.json"
  "cursor|User/settings.json"
  "cursor|User/keybindings.json"
  "cursor|User/snippets"
)

# Directories managed as git submodules. sync.sh must NOT copy these — they
# are checked out by `git submodule update --init` from their own upstreams.
SUBMODULE_DIRS=( nvim matugen-themes )

# Derived: the app dir names handled by EDITOR_SUBSET. These are skipped by the
# bulk ~/.config loop and only synced path-by-path below.
EDITOR_SUBSET_APP=( $(printf '%s\n' "${EDITOR_SUBSET[@]}" | cut -d'|' -f1 | sort -u) )

# Generic noise that shows up inside otherwise-trackable config dirs.
NOISE=(
  '.cache' 'Cache' 'CachedData' 'CachedExtensions' 'GPUCache'
  'Code Cache' 'DawnCache' 'DawnGraphiteCache' 'DawnWebGPUCache'
  'blob_storage' 'Service Worker' 'Session Storage' 'Local Storage'
  'IndexedDB' 'databases' 'logs' 'log' 'tmp' 'temp'
  'node_modules' '.git' '.ruff_cache' '.dart_tool'
  'SingletonLock' 'SingletonSocket' 'SingletonCookie'
  '*.log' '*.lock' '*.tmp' '*.bak' '*.old' '*.swp'
)

# Config dirs that are pure cache/state despite living in ~/.config.
also_exclude() {
  printf '%s\n' "${APP_STATE[@]}" | sed 's/^/--exclude=/'
  printf '%s\n' "${NOISE[@]}"    | sed 's/^/--exclude=/'
  # runtime locks KDE/Qt apps leave behind
  printf '%s\n' kactivitymanagerdrc kiorc trashrc ktimezonedrc kconf_updaterc \
    | sed 's/^/--exclude=/'
}

# Guard: rsync args must not contain spaces or they'd split into bogus
# source paths. Anything with a space gets dropped rather than break the sync.
EXCL=( $(also_exclude | grep -v '[[:space:]]') )

# ---------------------------------------------------------------------------
# ~/.config
# ---------------------------------------------------------------------------
log "Syncing ~/.config ..."
for entry in "$HOME/.config"/* "$HOME/.config"/.[!.]*; do
  [ -e "$entry" ] || continue
  name="$(basename "$entry")"

  # Skip app-state entries entirely
  skip=0
  for state in "${APP_STATE[@]}" "${EDITOR_SUBSET_APP[@]}" "${SUBMODULE_DIRS[@]}"; do
    [ "$name" = "$state" ] && skip=1 && break
  done
  [ $skip -eq 1 ] && continue

  # Single files
  if [ -f "$entry" ] && [ ! -L "$entry" ]; then
    rsync -a "$entry" "$CONF_DIR/" 2>/dev/null || \
      warn "skipped $name"
    continue
  fi

  # Directories: prune the noise inside.
  # Trailing slash on the source + pre-created dest => contents land in
  # dest/ directly. Without it rsync nests an extra basename level.
  mkdir -p "$CONF_DIR/$name"
  rsync -a --delete-delay "${EXCL[@]}" "$entry/" "$CONF_DIR/$name/" 2>/dev/null || \
    warn "skipped $name"
done

# ---------------------------------------------------------------------------
# Editors: track only the settings we care about, never the 190M of state
# ---------------------------------------------------------------------------
log "Syncing editor settings ..."
for spec in "${EDITOR_SUBSET[@]}"; do
  app="${spec%%|*}"
  rel="${spec#*|}"
  src="$HOME/.config/$app/$rel"
  dst="$CONF_DIR/$app/$rel"

  [ -e "$src" ] || continue
  mkdir -p "$dst"

  if [ -d "$src" ]; then
    rsync -a --delete-delay "${EXCL[@]}" "$src/" "$dst/" 2>/dev/null
  else
    cp -f "$src" "$dst"
  fi
  echo "  $app/$rel"
done

# Drop the broken symlink (points at a directory that no longer exists)
rm -f "$CONF_DIR/wallust"

# ---------------------------------------------------------------------------
# Home dotfiles
# ---------------------------------------------------------------------------
log "Syncing home dotfiles ..."
for f in .bashrc .bash_profile .bash_logout .profile .zshrc .zshenv \
         .gtkrc-2.0 .xinitrc .Xresources .dircolors .gitignore_global; do
  [ -f "$HOME/$f" ] && cp -f "$HOME/$f" "$HOME_DIR/$f"
done

# ~/.local/bin — our own scripts (not package-managed binaries)
log "Syncing ~/.local/bin scripts ..."
mkdir -p "$HOME_DIR/.local/bin"
for f in "$HOME/.local/bin"/*; do
  [ -f "$f" ] || continue
  base="$(basename "$f")"
  # Skip huge downloaded binaries and package-managed shims
  case "$base" in
    agy|agy.*|cpak|cpak-storaged|disktree|codex|pi|zeron) continue ;;
  esac
  [ -L "$f" ] && continue
  rsync -a "$f" "$HOME_DIR/.local/bin/$base"
done

# ---------------------------------------------------------------------------
# Themes, icons, fonts
# ---------------------------------------------------------------------------
log "Syncing themes / icons / fonts ..."
mkdir -p "$THEME_DIR"
[ -d "$HOME/.themes" ] && rsync -a "$HOME/.themes/" "$THEME_DIR/gtk/" 2>/dev/null || true
[ -d "$HOME/.icons" ]   && rsync -a "$HOME/.icons/"   "$THEME_DIR/icons/" 2>/dev/null || true
[ -d "$HOME/.config/Kvantum" ] && rsync -a "${EXCL[@]}" "$HOME/.config/Kvantum/" "$THEME_DIR/gtk/Kvantum/" 2>/dev/null || true

# Fonts: only user-installed ones, never system-wide
if [ -d "$HOME/.local/share/fonts" ]; then
  rsync -a "$HOME/.local/share/fonts/" "$THEME_DIR/fonts/" 2>/dev/null || true
fi

# ---------------------------------------------------------------------------
# Wallpapers
# ---------------------------------------------------------------------------
log "Syncing wallpapers ..."
if [ -d "$HOME/Pictures/Wallpapers" ]; then
  mkdir -p "$ASSET_DIR/wallpapers"
  rsync -a --delete-delay "$HOME/Pictures/Wallpapers/" "$ASSET_DIR/wallpapers/" 2>/dev/null
  echo "  $(find "$ASSET_DIR/wallpapers" -type f | wc -l) files, $(du -sh "$ASSET_DIR/wallpapers" | cut -f1)"
fi

# ---------------------------------------------------------------------------
# Avatar
# ---------------------------------------------------------------------------
# ~/.face is just the greeter/login profile picture — a plain JPEG, not
# biometric data. Safe to track.
log "Syncing avatar ..."
if [ -f "$HOME/.face" ]; then
  mkdir -p "$ASSET_DIR"
  cp -f "$HOME/.face" "$ASSET_DIR/avatar.jpg"
  echo "  avatar.jpg ($(du -h "$ASSET_DIR/avatar.jpg" | cut -f1))"
fi

# ---------------------------------------------------------------------------
# Secrets -> templates
# ---------------------------------------------------------------------------
log "Writing secret templates ..."
mkdir -p "$HOME_DIR/.ssh"
cat > "$HOME_DIR/.ssh/config.example" <<'EOF'
# Copy to ~/.ssh/config and fill in.
Host github.com
  HostName github.com
  User git
  IdentityFile ~/.ssh/id_ed25519
  AddKeysToAgent yes
EOF

if [ -f "$HOME/.gitconfig" ]; then
  # Strip credentials section, keep user identity
  sed '/^\[credential/,/^$/d' "$HOME/.gitconfig" > "$HOME_DIR/.gitconfig.example"
fi

# ---------------------------------------------------------------------------
# Package manifests
# ---------------------------------------------------------------------------
if [ -x "$PKG_DIR/generate.sh" ] || [ -f "$PKG_DIR/generate.sh" ]; then
  log "Generating package manifests ..."
  bash "$PKG_DIR/generate.sh" || warn "package manifest generation failed"
fi

# ---------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------
log "Done. Repo size: $(du -sh "$DOTDIR" | cut -f1)"
warn "Secrets are NOT included (.ssh keys, .gnupg, .env.local)."
warn "External git repos are NOT vendored — see PROJECTS.md + restore-projects.sh"
warn "Review with: git status"