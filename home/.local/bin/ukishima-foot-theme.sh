#!/bin/sh
# Generate foot colors from Ukishima's ghostty palette (wallpaper-driven).
# Triggered by ukishima-foot-theme.path whenever wallcolors.py regenerates.
set -eu
SRC="${XDG_CACHE_HOME:-$HOME/.cache}/ukishima/ghostty-colors"
DST="$HOME/.config/foot/colors.ini"
[ -f "$SRC" ] || exit 0
python3 - "$SRC" "$DST" <<'EOF'
import sys
src, dst = sys.argv[1], sys.argv[2]
vals = {}
for line in open(src):
    line = line.strip()
    if line.startswith('palette'):
        _, rest = line.split('=', 1)
        idx, col = rest.split('=', 1)
        vals[f'p{idx.strip()}'] = col.strip().lstrip('#')
    elif '=' in line:
        k, v = line.split('=', 1)
        vals[k.strip()] = v.strip().lstrip('#')
with open(dst, 'w') as f:
    f.write('# Generated by ukishima-foot-theme.sh from Ukishima ghostty-colors — do not hand-edit\n')
    f.write('# Light ramp -> [colors-light] (foot >= 1.28 has no plain [colors])\n')
    f.write('[colors-light]\n')
    f.write(f"foreground={vals.get('foreground', '222120')}\n")
    f.write(f"background={vals.get('p0', 'eeeded')}\n")
    f.write(f"selection-foreground={vals.get('selection-foreground', '222120')}\n")
    f.write(f"selection-background={vals.get('selection-background', 'ceccca')}\n")
    for i in range(8):
        f.write(f"regular{i}={vals.get(f'p{i}', '000000')}\n")
    for i in range(8):
        f.write(f"bright{i}={vals.get(f'p{i + 8}', '000000')}\n")
EOF
# live-reload running foot instances (SIGUSR1); harmless if none
pkill -USR1 -x foot 2>/dev/null || true
