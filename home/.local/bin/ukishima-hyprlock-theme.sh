#!/bin/sh
# Regenerate ~/.config/hypr/colors.conf from Ukishima's matugen palette.
# Triggered by ukishima-hyprlock-theme.path whenever the palette changes.
set -eu
SRC="${XDG_CACHE_HOME:-$HOME/.cache}/ukishima/colors.json"
DST="$HOME/.config/hypr/colors.conf"
[ -f "$SRC" ] || exit 0
python3 - "$SRC" "$DST" <<'EOF'
import json, sys
src, dst = sys.argv[1], sys.argv[2]
c = json.load(open(src))
def h(k, fb):
    return str(c.get(k, fb)).lstrip('#')
m = {
    'source_color': h('primary', 'b6b3af'),
    'secondary': h('subtle', 'bfbbb5'),
    'on_secondary_container': h('on_primary_container', 'dddbda'),
    # Lock bg is always a darkened blur, so text stays fixed near-white
    # instead of following the palette's surface-tuned tokens.
    'light': 'f2f5f9',
    'color8': h('faint', '76716b'),
}
with open(dst, 'w') as f:
    f.write('# Generated by ukishima-hyprlock-theme.sh — do not hand-edit\n')
    f.write('# Source: Ukishima matugen palette (~/.cache/ukishima/colors.json)\n')
    for k, v in m.items():
        f.write(f'${k} = rgb({v})\n')
EOF
