#!/usr/bin/env bash
# generate.sh — snapshot the installed package set so a new machine can be
# rebuilt to match. Run via ../sync.sh or standalone.

set -uo pipefail

PKG_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

{
  echo "# CachyOS / Arch — explicit packages"
  echo "# Generated by packages/generate.sh on $(date +%Y-%m-%d)"
  echo "# Install: sudo pacman -S --needed - < packages/pacman.txt"
  echo
  echo "## Desktop environment / display"
  echo "hyprland"
  echo "quickshell-git"
  echo "hypridle"
  echo "hyprlock-git"
  echo "hyprpaper"
  echo "swaybg"
  echo "swayidle"
  echo "swaylock"
  echo "wtype"
  echo "xdg-desktop-portal-hyprland"
  echo "xdg-desktop-portal-gtk"
  echo "uwsm"
  echo "greetd"
  echo "greetd-tuigreet"
  echo "wl-clipboard"
  echo "grim"
  echo "slurp"
  echo "swappy"
  echo "libinput"
  echo "seatd"
  echo
  echo "## Shell / terminal"
  echo "zsh"
  echo "bash"
  echo "fish"
  echo "starship"
  echo "ttf-jetbrains-mono"
  echo "ttf-jetbrains-mono-nerd"
  echo "eza"
  echo "bat"
  echo "fzf"
  echo "ripgrep"
  echo "fd"
  echo "zoxide"
  echo "atuin"
  echo "yazi"
  echo "delta"
  echo "lazygit"
  echo "btop"
  echo "fastfetch"
  echo
  echo "## Neovim"
  echo "neovim"
  echo "lua-language-server"
  echo
  echo "## Theming"
  echo "matugen"
  echo "pywal"
  echo "wallust"
  echo "ttf-material-symbols-variable-git"
  echo
  echo "## Media / audio"
  echo "pipewire"
  echo "pipewire-pulse"
  echo "pipewire-jack"
  echo "wireplumber"
  echo "playerctl"
  echo "pwvucontrol"
  echo "mpv"
  echo "smplayer"
  echo "spotifast"
  echo
  echo "## Development"
  echo "git"
  echo "base-devel"
  echo "curl"
  echo "wget"
  echo "unzip"
  echo "pkgconf"
  echo "cmake"
  echo "ninja"
  echo "rustup"
  echo "go"
  echo "jdk17-openjdk"
  echo "android-sdk"
  echo "android-platform-tools"
  echo "nodejs"
  echo "npm"
  echo "bun"
  echo "pnpm"
} > "$PKG_DIR/pacman.txt"

# AUR packages actually installed
{
  echo "# AUR packages installed on $(date +%Y-%m-%d)"
  echo "# Install: paru --needed - < packages/aur.txt"
  echo
  paru -Qqm 2>/dev/null | sort -u
} > "$PKG_DIR/aur.txt"

# Flatpaks
{
  echo "# Flatpaks installed on $(date +%Y-%m-%d)"
  echo "# Install: flatpak install -y --noninteractive $(grep -v '^#' packages/flatpak.txt | tr '\n' ' ')"
  echo
  flatpak list --app --columns=application 2>/dev/null | sort -u
} > "$PKG_DIR/flatpak.txt"

# Font list, for reference
if command -v fc-list >/dev/null; then
  {
    echo "# Fonts referenced by name on $(date +%Y-%m-%d)"
    echo "# Regenerate with: fc-list : family | tr ',' '\n' | sort -u"
    echo
    fc-list : family 2>/dev/null | tr ',' '\n' | sed 's/^ *//' | sort -u | head -300
  } > "$PKG_DIR/fonts.txt"
fi

echo "  pacman.txt  $(wc -l < "$PKG_DIR/pacman.txt") lines"
echo "  aur.txt     $(wc -l < "$PKG_DIR/aur.txt") lines"
echo "  flatpak.txt $(wc -l < "$PKG_DIR/flatpak.txt") lines"